import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';

const read = path => readFile(new URL(path, import.meta.url), 'utf8');
const [core, plugin, markings, ui, theme] = await Promise.all([
  read('./src/core.cjs'), read('./src/plugin.cjs'), read('./src/markings.css'),
  read('./src/ui.css'), read('../theme.css')
]);
const main = `/* Inkstone Annotations 1.0.0. MIT License. Generated by build.mjs. */\n` +
  `const annotationCore = (() => { const module = { exports: {} };\n${core}\nreturn module.exports; })();\n${plugin}`;
const start = '/* INKSTONE_ANNOTATIONS_START */';
const end = '/* INKSTONE_ANNOTATIONS_END */';
const baseTheme = theme.includes(start) ? theme.slice(0, theme.indexOf(start)).trimEnd() : theme.trimEnd();
await Promise.all([
  writeFile(new URL('./main.js', import.meta.url), main),
  writeFile(new URL('./styles.css', import.meta.url), markings + '\n' + ui),
  writeFile(new URL('../theme.css', import.meta.url), `${baseTheme}\n\n${start}\n${markings}\n${end}\n`)
]);
await mkdir(new URL('./examples/', import.meta.url), { recursive: true });
await copyFile(new URL('../examples/划线与备注示例.md', import.meta.url), new URL('./examples/划线与备注示例.md', import.meta.url));
console.log('Built the dependency-free plugin and shared annotation styles.');
