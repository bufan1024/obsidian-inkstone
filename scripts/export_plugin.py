#!/usr/bin/env python3
"""Export the maintained annotation plugin as a self-contained GitHub repository."""

from __future__ import annotations

import argparse
import json
from pathlib import Path, PurePosixPath
import posixpath
import re
import sys
import tempfile
from urllib.parse import urlsplit, urlunsplit


ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = "https://github.com/bufan1024/obsidian-inkstone"
REPOSITORY_URL = "https://github.com/bufan1024/obsidian-inkstone-annotations"
COPY_FILES = {
    **{name: f"annotations/{name}" for name in (
        "main.js", "styles.css", "manifest.json", "LICENSE",
        "src/core.cjs", "src/editor.cjs", "src/views.cjs", "src/annotation-menu.cjs",
        "src/plugin.cjs", "src/markings.css", "src/ui.css",
        "tests/core.test.cjs", "tests/editor.test.cjs", "tests/views.test.cjs",
        "tests/plugin.test.cjs", "tests/lifecycle.test.cjs", "examples/划线与备注示例.md",
    )},
    "assets/annotate.gif": "assets/annotate.gif",
    "assets/review-export.gif": "assets/review-export.gif",
}
README_FILES = {"README.md": "annotations/README.en.md", "README.zh-CN.md": "annotations/README.md"}
SOURCE_FILES = tuple(COPY_FILES.values()) + tuple(README_FILES.values())
VERSION = re.compile(r"(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)")

BUILD_SCRIPT = """import { readFile, writeFile } from 'node:fs/promises';

const read = path => readFile(new URL(path, import.meta.url), 'utf8');
const [core, editor, views, menu, plugin, markings, ui, manifest] = await Promise.all([
  read('./src/core.cjs'), read('./src/editor.cjs'), read('./src/views.cjs'), read('./src/annotation-menu.cjs'), read('./src/plugin.cjs'), read('./src/markings.css'),
  read('./src/ui.css'), read('./manifest.json')
]);
const bundle = (name, source) => `const ${name} = (() => { const module = { exports: {} };\\n${source}\\nreturn module.exports; })();\\n`;
const main = `/* Inkstone Annotations ${JSON.parse(manifest).version}. MIT License. Generated by build.mjs. */\\n` +
  bundle('annotationCore', core) + bundle('annotationEditor', editor) + bundle('annotationViews', views) + bundle('annotationMenu', menu) + plugin;
await Promise.all([
  writeFile(new URL('./main.js', import.meta.url), main),
  writeFile(new URL('./styles.css', import.meta.url), markings + '\\n' + ui)
]);
console.log('Built the standalone annotation plugin.');
"""

WORKFLOW = """name: Plugin checks

on: [push, pull_request]

permissions:
  contents: read

jobs:
  check:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v6
      - uses: actions/setup-node@v7
        with:
          node-version: '22'
      - name: Build and verify committed artifacts
        run: |
          npm run build
          git diff --exit-code -- main.js styles.css
      - name: Test annotations
        run: npm test
"""


def read_source(relative: str) -> bytes:
    path = PurePosixPath(relative)
    if path.is_absolute() or any(part in ("..", ".git", ".qa") for part in path.parts):
        raise ValueError(f"Unsafe source path: {relative}")
    source = ROOT.joinpath(*path.parts)
    current = source
    while current != ROOT:
        if current.is_symlink():
            raise ValueError(f"Source symlinks are not allowed: {relative}")
        current = current.parent
    if not source.is_file() or ROOT.resolve() not in source.resolve().parents:
        raise ValueError(f"Required plugin source is missing: {relative}")
    return source.read_bytes()


def json_bytes(value: object) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def repository_url(value: str) -> str:
    value = value.rstrip("/")
    if not re.fullmatch(r"https://github\.com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", value):
        raise ValueError("--repository-url must be an HTTPS GitHub repository URL")
    return value.removesuffix(".git")


def rewrite_links(text: str, exported: set[str]) -> str:
    """Keep exported files local; resolve other links from the original annotations folder."""
    def replace(match):
        target = match.group(2)
        url = urlsplit(target)
        if url.scheme or url.netloc or not url.path or url.path in exported:
            return match.group(0)
        upstream_path = posixpath.normpath(posixpath.join("annotations", url.path))
        destination = urlunsplit(("https", "github.com", f"/bufan1024/obsidian-inkstone/blob/main/{upstream_path}", url.query, url.fragment))
        return f"{match.group(1)}({destination})"
    return re.sub(r"(!?\[[^\]]*\])\(([^)]+)\)", replace, text)


def readme(data: bytes, language: str, repository: str, exported: set[str]) -> bytes:
    text = data.decode("utf-8")
    text = text.replace("[简体中文](README.md) · English\n", "")
    text = text.replace("简体中文 · [English](README.en.md)\n", "")
    # The source guides also advertise the standalone repo. Replace that one paragraph
    # with the local distribution's release and direct-download links below.
    text = re.sub(r"(?m)^(?:The standalone plugin release and directory submission use |Standalone plugin releases use ).*\n", "", text)
    text = re.sub(r"(?m)^(?:独立插件发布与社区目录提交使用 |独立插件使用 ).*\n", "", text)
    downloads = " · ".join(f"[{name}]({repository}/releases/latest/download/{name})" for name in ("main.js", "manifest.json", "styles.css"))
    if language == "en":
        language_bar = "[简体中文](README.zh-CN.md) · English"
        introduction = f"Standalone plugin files: [latest release]({repository}/releases/latest) · {downloads}."
        demos = "## Demos\n\n![Select text, choose a style, and save a thought](assets/annotate.gif)\n\n![Review annotations and export excerpts](assets/review-export.gif)"
        text = text.replace(f"[GitHub Releases]({UPSTREAM}/releases/latest)", f"[GitHub Releases]({repository}/releases/latest)")
        text = text.replace("When using the source repository or reading kit, run this from its root directory:", f"The optional installer belongs to the [upstream theme repository]({UPSTREAM}) or its reading kit, and is not included here. Run the following only from the upstream checkout or extracted kit:")
        text = re.split(r"(?m)^## Development and license\s*$", text, maxsplit=1)[0].rstrip()
        development = f"""## Development and license

Use Node.js 22 or later. No package installation or third-party build dependencies are required:

```sh
node build.mjs
node --test tests/*.test.cjs
```

`npm run build` and `npm test` run the same commands. The build reads only this repository's `src/` and `manifest.json`, and generates `main.js` and `styles.css`.

Plugin source is maintained once, in the [upstream annotations directory]({UPSTREAM}/tree/main/annotations). Submit source changes there, then regenerate this distribution with the upstream `scripts/export_plugin.py`; do not maintain a divergent copy here. The local example is an exported copy of the upstream example.

[MIT License](LICENSE). For bug reports, include your Obsidian version, operating system, view mode, a minimal note, and relevant CSS snippets.
"""
    else:
        language_bar = "简体中文 · [English](README.md)"
        introduction = f"独立插件：[最新 Release]({repository}/releases/latest) · {downloads}。"
        demos = "## 操作演示\n\n![选中文字、选择样式并保存想法](assets/annotate.gif)\n\n![查看标注侧栏并导出摘录](assets/review-export.gif)"
        text = text.replace("使用完整仓库或合集中的安装脚本时", f"使用[上游主题仓库]({UPSTREAM})或合集中的安装脚本时（本独立插件仓库不含安装器）")
        text = re.split(r"(?m)^## 开发\s*$", text, maxsplit=1)[0].rstrip()
        development = f"""## 开发与许可

使用 Node.js 22 或更新版本，无需安装依赖：

```sh
node build.mjs
node --test tests/*.test.cjs
```

也可运行 `npm run build` 和 `npm test`。构建仅使用本仓库的 `src/` 和 `manifest.json`，生成 `main.js` 与 `styles.css`。

插件源码只在[上游 annotations 目录]({UPSTREAM}/tree/main/annotations)维护。请在那里提交源码修改，再用上游 `scripts/export_plugin.py` 重新导出此发行仓库，避免维护两份不同的源码。本地示例是上游示例的导出副本。

[MIT 许可](LICENSE)。反馈问题请附 Obsidian 版本、系统、视图、最小笔记片段及相关 CSS 代码片段。
"""
    title, separator, body = text.partition("\n")
    if not separator or not title.startswith("# "):
        raise ValueError("Plugin README must start with a Markdown title")
    result = f"{title}\n\n{language_bar}\n\n{introduction}\n\n{demos}\n\n{body.strip()}\n\n{development}"
    return rewrite_links(result, exported).encode("utf-8")


def collect_files(repository: str) -> dict[str, bytes]:
    sources = {name: read_source(name) for name in SOURCE_FILES}
    files = {destination: sources[source] for destination, source in COPY_FILES.items()}
    manifest = json.loads(files["manifest.json"])
    for field in ("version", "minAppVersion"):
        if not isinstance(manifest.get(field), str) or not VERSION.fullmatch(manifest[field]):
            raise ValueError(f"Invalid plugin manifest {field}; expected x.y.z")
    files.update({
        "build.mjs": BUILD_SCRIPT.encode("utf-8"),
        "package.json": json_bytes({
            "name": manifest["id"], "version": manifest["version"], "private": True,
            "scripts": {"build": "node build.mjs", "test": "node --test tests/*.test.cjs"},
            "engines": {"node": ">=22"},
        }),
        "versions.json": json_bytes({manifest["version"]: manifest["minAppVersion"]}),
        ".github/workflows/check.yml": WORKFLOW.encode("utf-8"),
    })
    exported = set(files) | set(README_FILES)
    for destination, source in README_FILES.items():
        files[destination] = readme(sources[source], "en" if destination == "README.md" else "zh", repository, exported)
    return files


def check_destination(destination: Path) -> None:
    if destination.is_symlink():
        raise ValueError(f"Output symlinks are not allowed: {destination}")
    if destination.exists() and (not destination.is_dir() or any(destination.iterdir())):
        raise ValueError(f"Output directory is not empty: {destination}")


def export(destination: Path, repository: str = REPOSITORY_URL) -> int:
    destination = destination.expanduser().absolute()
    check_destination(destination)
    files = collect_files(repository_url(repository))
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".inkstone-plugin-export-", dir=destination.parent) as temporary:
        stage = Path(temporary) / "repository"
        stage.mkdir()
        for relative, content in files.items():
            target = stage / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
        check_destination(destination)
        if destination.exists():
            destination.rmdir()  # Only an empty directory passes the check above.
        stage.rename(destination)
    return len(files)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True, help="New or empty standalone repository directory")
    parser.add_argument("--repository-url", default=REPOSITORY_URL, help="Public GitHub repository used for release links")
    args = parser.parse_args(argv)
    try:
        count = export(args.output_dir, args.repository_url)
        print(f"Exported {count} plugin repository files to {args.output_dir}")
        print("Run npm run build and npm test in that directory before committing or publishing.")
        return 0
    except (OSError, ValueError, KeyError) as error:
        print(f"Plugin export failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
